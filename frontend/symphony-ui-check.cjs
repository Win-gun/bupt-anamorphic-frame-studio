const {chromium}=require('@playwright/test');
const fs=require('fs'),path=require('path'),assert=require('node:assert/strict');
(async()=>{
 const out=path.resolve(__dirname,'../examples/autumn-symphony');
 const browser=await chromium.launch({channel:'chrome',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:960}}),errors=[];
 page.on('pageerror',e=>errors.push(String(e)));
 await page.goto('http://127.0.0.1:8000');
 await page.getByRole('button',{name:/枫光奏鸣/}).click();
 assert.equal(await page.getByText('空间色彩',{exact:true}).count(),0);
 assert.equal(await page.getByText('悬浮距离 m',{exact:true}).count(),0);
 await page.locator('input[type=file][accept="image/*"]').setInputFiles(path.resolve(__dirname,'../examples/v2/jiqi-qiuyun/original.png'));
 const submitted=page.waitForResponse(r=>r.url().endsWith('/api/jobs')&&r.request().method()==='POST');
 await page.getByRole('button',{name:'快速预览',exact:true}).click();
 const id=(await(await submitted).json()).id;
 await page.locator('.downloads a').first().waitFor({timeout:180000});
 const job=await(await page.request.get('http://127.0.0.1:8000/api/jobs/'+id)).json();
 assert.equal(job.status,'completed',job.error);assert.equal(job.metrics.artwork.template,'autumn_symphony');
 assert.ok(job.metrics.metrics.foreground_coverage>=.98);
 await page.getByRole('button',{name:'三维场景',exact:true}).click();
 await page.locator('.viewport img').waitFor();
 await page.waitForFunction(()=>{const i=document.querySelector('.viewport img');return i&&i.complete&&i.naturalWidth>0;});
 await page.screenshot({path:path.join(out,'ui-desktop.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 const fit=await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth);assert.ok(fit);
 await page.screenshot({path:path.join(out,'ui-mobile.png'),fullPage:true});
 assert.deepEqual(errors,[]);
 fs.writeFileSync(path.join(out,'ui-check.json'),JSON.stringify({passed:true,actual_render_job:id,poster_coverage:job.metrics.metrics.foreground_coverage,mobile_no_overflow:fit,page_errors:errors},null,2));
 await browser.close();console.log('SYMPHONY_UI_PASS',id);
})().catch(e=>{console.error(e);process.exit(1)});
