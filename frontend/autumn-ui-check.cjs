const { chromium } = require('@playwright/test');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
(async () => {
  const browser = await chromium.launch({channel:'chrome', headless:true});
  const page = await browser.newPage({viewport:{width:1440,height:900}});
  const out = path.resolve(__dirname, '../examples/autumn-resonance');
  fs.mkdirSync(out,{recursive:true});
  let posted;
  const pageErrors = [];
  page.on("pageerror", error => pageErrors.push(String(error)));
  await page.route('**/api/jobs', async route => {
    if (route.request().method() !== 'POST') return route.continue();
    const body = route.request().postDataBuffer().toString('utf8');
    const match = body.match(/name="config"\r\n\r\n([^\r\n]+)/);
    assert.ok(match, 'multipart config'); posted = JSON.parse(match[1]);
    await route.fulfill({json:{id:'ui-test'}});
  });
  await page.route('**/api/jobs/ui-test', route => route.fulfill({json:{id:'ui-test',status:'failed',progress:0}}));
  await page.goto(process.env.UI_URL || 'http://127.0.0.1:8000');
  await page.locator('input[type=file][accept="image/*"]').setInputFiles(path.resolve(__dirname,'../examples/v2/jiqi-qiuyun/original.png'));
  await page.getByRole('button',{name:/秋韵光影舱/}).click();
  for (const v of ['warm','cool','balanced']) await page.locator('label').filter({hasText:'色调'}).locator('select').selectOption(v);
  await page.getByLabel('光照强度',{exact:true}).fill('1.25');
  await page.getByLabel('纹理强度 mm').fill('0.3');
  await page.getByText('高级参数',{exact:true}).click();
  await page.locator('label').filter({hasText:'渲染引擎'}).locator('select').selectOption('cycles');
  await page.screenshot({path:path.join(out,'ui-desktop.png'),fullPage:true});
  const submission = page.waitForResponse(response => response.url().endsWith('/api/jobs') && response.request().method() === 'POST');
  await page.getByRole('button',{name:/动态测试/}).click();
  await submission;
  assert.equal(posted.frame.template,'autumn_resonance_cube');
  assert.equal(posted.autumn.variant,'balanced'); assert.equal(posted.autumn.light_intensity,1.25);
  assert.ok(Math.abs(posted.autumn.texture_strength_m - 0.0003) < 1e-10);
  assert.equal(posted.autumn.engine,'cycles');
  assert.deepEqual([posted.render.duration,posted.render.fps,posted.render.scale,posted.render.samples,posted.render.animation,posted.render.video],[7.5,24,0.125,8,true,true]);
  assert.equal(posted.cube.layout,'floating');
  for (const name of ['极光悬浮','柔光纵深','玻璃叠层','楼体内嵌立方体','嵌入立方（原版）']) await page.getByRole('button',{name:new RegExp(name.replace(/[（）]/g,'.'))}).click();
  await page.getByText('Legacy / 经典样式').click();
  for (const name of ['影院画框','悬浮画框','玻璃画框']) await page.getByRole('button',{name,exact:true}).click();
  await page.getByRole('button',{name:/秋韵光影舱/}).click();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(out,'ui-mobile.png'),fullPage:true});
  const overflow = await page.evaluate(() => ({body:document.documentElement.scrollWidth, viewport:innerWidth}));
  assert.ok(overflow.body <= overflow.viewport, JSON.stringify(overflow));
  assert.deepEqual(pageErrors, []);
  fs.writeFileSync(path.join(out,'ui-check.json'),JSON.stringify({passed:true,intercepted_render_submission:true,real_render_created_by_this_test:false,page_errors:pageErrors,mobile:overflow,submitted_config:posted},null,2));
  await browser.close(); console.log('PASS: autumn config, motion, templates and mobile overflow');
})().catch(e => { console.error(e); process.exit(1); });
