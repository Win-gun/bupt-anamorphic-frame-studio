const { chromium } = require('@playwright/test');
const path = require('path');
const fs = require('fs');
(async () => {
  const browser = await chromium.launch({channel:'chrome',headless:true});
  const page = await browser.newPage({viewport:{width:1600,height:1000}});
  const errors=[];
  page.on('pageerror',e=>errors.push(String(e)));
  await page.goto('http://127.0.0.1:8000');
  await page.getByRole('heading',{name:'调整参数'}).waitFor();
  await page.locator('input[type=file]').setInputFiles(path.resolve(__dirname,'../examples/poster.png'));
  await page.getByRole('button',{name:/开始渲染/}).click();
  await page.locator('.downloads a').first().waitFor({timeout:120000});
  await page.locator('.viewport img').waitFor();
  const src = await page.locator('.viewport img').getAttribute('src');
  const img=await page.locator('.viewport img').evaluate(im=>({loaded:im.complete&&im.naturalWidth>0,width:im.naturalWidth,height:im.naturalHeight}));
  if (!img.loaded) throw Error('Preview failed to load');
  await page.screenshot({path:path.resolve(__dirname,'../examples/ui-desktop.png'),fullPage:true});
  const jobURL = src.replace('/outputs/','/api/jobs/').split('/').slice(0,4).join('/');
  const report=await page.request.get('http://127.0.0.1:8000'+jobURL);
  const job=await report.json();
  if(job.status!=='completed')throw Error(JSON.stringify(job));
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.resolve(__dirname,'../examples/ui-mobile.png'),fullPage:true});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
  fs.writeFileSync(path.resolve(__dirname,'../examples/ui-check.json'),JSON.stringify({status:job.status,id:job.id,preview:img,pageErrors:errors,mobileOverflow:overflow},null,2));
  if(errors.length||overflow)throw Error(JSON.stringify({errors,overflow}));
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
